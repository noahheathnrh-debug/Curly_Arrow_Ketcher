import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { basename, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const iconsDirectory = fileURLToPath(
  new URL('../src/assets/icons/files/', import.meta.url),
);
const outputFile = fileURLToPath(
  new URL(
    '../src/components/Icon/generated/iconSprite.generated.ts',
    import.meta.url,
  ),
);

const readAttribute = (attributes, name) =>
  attributes.match(new RegExp(`\\b${name}=(['"])(.*?)\\1`, 'i'))?.[2];

const removeAttribute = (attributes, name) =>
  attributes.replace(new RegExp(`\\s+${name}=(['"])(.*?)\\1`, 'gi'), '');

const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const prefixInternalIds = (markup, prefix) => {
  const ids = Array.from(
    markup.matchAll(/\bid=(['"])(.*?)\1/gi),
    (match) => match[2],
  );

  return ids.reduce((result, id) => {
    const escapedId = escapeRegExp(id);
    const prefixedId = `${prefix}-${id}`;

    return result
      .replace(
        new RegExp(`(\\bid=(['"]))${escapedId}\\2`, 'g'),
        `$1${prefixedId}$2`,
      )
      .replace(new RegExp(`url\\(#${escapedId}\\)`, 'g'), `url(#${prefixedId})`)
      .replace(
        new RegExp(`((?:xlink:)?href=(['"]))#${escapedId}\\2`, 'g'),
        `$1#${prefixedId}$2`,
      );
  }, markup);
};

const toSafeId = (value) =>
  Array.from(value, (character) =>
    /[a-zA-Z0-9_-]/.test(character)
      ? character
      : `u${character.codePointAt(0).toString(16)}`,
  ).join('');

const iconFiles = (await readdir(iconsDirectory))
  .filter((fileName) => extname(fileName).toLowerCase() === '.svg')
  .sort((first, second) => first.localeCompare(second));

const descriptors = {};
const symbols = [];

for (const fileName of iconFiles) {
  const iconName = basename(fileName, '.svg');
  const symbolId = `ketcher-icon-${toSafeId(iconName)}`;
  const source = await readFile(`${iconsDirectory}/${fileName}`, 'utf8');
  const svg = source.match(/<svg\b([^>]*)>([\s\S]*?)<\/svg>/i);

  if (!svg) {
    throw new Error(`Unable to parse ${fileName}`);
  }

  const attributes = svg[1];
  const width = readAttribute(attributes, 'width') ?? '24';
  const height = readAttribute(attributes, 'height') ?? '24';
  const viewBox =
    readAttribute(attributes, 'viewBox') ?? `0 0 ${width} ${height}`;
  const symbolAttributes = [
    'width',
    'height',
    'viewBox',
    'xmlns',
    'xmlns:xlink',
  ]
    .reduce(removeAttribute, attributes)
    .trim();
  const contents = prefixInternalIds(svg[2], symbolId);

  descriptors[iconName] = { symbolId, width, height, viewBox };
  symbols.push(
    `<symbol id="${symbolId}" viewBox="${viewBox}"${
      symbolAttributes ? ` ${symbolAttributes}` : ''
    }>${contents}</symbol>`,
  );
}

const spriteMarkup = `<svg id="ketcher-icon-sprite" xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="position:absolute;width:0;height:0;overflow:hidden">${symbols.join(
  '',
)}</svg>`;
const generatedSource = `/* This file is generated by scripts/generate-icon-sprite.mjs. */
export const iconSpriteMarkup = ${JSON.stringify(spriteMarkup)};

export const iconSpriteDescriptors = ${JSON.stringify(
  descriptors,
  null,
  2,
)} as const;

export type IconSpriteName = keyof typeof iconSpriteDescriptors;
`;

await mkdir(dirname(outputFile), { recursive: true });
const prettierConfig = (await prettier.resolveConfig(outputFile)) ?? {};
await writeFile(
  outputFile,
  await prettier.format(generatedSource, {
    ...prettierConfig,
    filepath: outputFile,
  }),
  'utf8',
);
